/**
 * Given a character (e.g. 'ሀ' or 'ሁ' or 'A'), find its corresponding family.
 */
export function findFidelFamily(character) {
  if (!character) return null;
  const trimmed = character.trim();
  return FIDEL_FAMILIES.find((fam) =>
    fam.base === trimmed || fam.forms.some((f) => f.symbol === trimmed)
  ) || null;
}
